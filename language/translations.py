# TRANSLATION FUNCTION
# ============================================================

def get_translation(language, key):
    """
    Translate interface text.

    Supports both:
        get_translation("Hindi", "patient_information")

    and:
        get_translation("Patient Information", "Hindi")

    This makes the function compatible with the current app.py.
    """

    # --------------------------------------------------------
    # Handle the argument order currently used by app.py
    # --------------------------------------------------------

    if language in TRANSLATIONS:

        selected_language = language
        requested_key = key

    elif key in TRANSLATIONS:

        selected_language = key
        requested_key = language

    else:

        selected_language = "English"
        requested_key = key

    # --------------------------------------------------------
    # Convert English display text into internal key
    # --------------------------------------------------------

    if requested_key in ENGLISH_TEXT_TO_KEY:

        requested_key = ENGLISH_TEXT_TO_KEY[
            requested_key
        ]

    # --------------------------------------------------------
    # Get selected language
    # --------------------------------------------------------

    language_data = TRANSLATIONS.get(
        selected_language,
        TRANSLATIONS["English"]
    )

    # --------------------------------------------------------
    # Return translation
    # --------------------------------------------------------

    return language_data.get(
        requested_key,
        TRANSLATIONS["English"].get(
            requested_key,
            requested_key
        )
    )